// Captures the preview frames for the cases whose UI now lives as a working prototype (Agentic, Engaze).
// Each frame is the prototype at the preview window's own size (1500 x 760, at 2x), plus the box of the control the cursor goes to next.
// Serve public/ on :4180 (python3 -m http.server 4180 --directory public), then: NODE_PATH=$(npm root -g) node tools/covers/shots.cjs
const { chromium } = require('playwright'); const fs = require('fs'); const { execFileSync } = require('child_process')
const OUT = 'public/images/loops'; const W = 1500, H = 760

const OC = 'http://localhost:4180/prototypes/order-confirmations/'
const B = `S=fresh();S.coach=false;`
const P = (u, view, tab) => B + `S.user='${u}';S.picked='${u}';S.view='${view}';S.tab=${tab ? `'${tab}'` : 'null'};`
const VAL = `S.o.stage='validated';`, BD = `S.o.diffs.forEach(d=>{if(d.own==='buyer')d.dec=d.sug});`, GD = `S.o.diffs.find(d=>d.id==='qty').dec='accept';S.o.diffs.find(d=>d.id==='date').dec='reject';`
const AGENTIC = [
  { id: 'worklist', cap: 'Operations opens what the agent has read', js: P('ops', 'worklist'), to: 'tr.click' },
  { id: 'read', cap: 'Every field read from the PDF, checked by a person', js: P('ops', 'order', 'Extraction'), to: '[data-a=validate]' },
  { id: 'review', cap: 'Each difference comes with a recommendation and its reasons', js: P('buyer', 'order', 'Differences') + VAL, to: '[data-a=dec]' },
  { id: 'decided', cap: 'The owner decides, line by line', js: P('buyer', 'order', 'Differences') + VAL + BD, to: '[data-a=savedec]' },
  { id: 'sent', cap: 'Nothing reaches the supplier until the buyer sends it', js: P('buyer', 'order', 'Differences') + VAL + BD + GD + `S.o.saved.buyer=true;S.o.saved.gr=true;S.o.sent=true;S.toast='Email sent to the supplier';`, to: null },
]
const EG = 'http://localhost:4180/prototypes/engaze/'
const hello = `document.querySelector('.hello h1')&&(document.querySelector('.hello h1').textContent='Good morning, Esha.')`
const ENGAZE = [
  { id: 'home', cap: 'Ask in your own words', js: hello, to: '.chips [data-k=leave]' },
  { id: 'think', cap: 'Engaze checks the balance, the policy and who to tell', act: async p => { await p.click('.chips [data-k=leave]'); await p.waitForTimeout(1500) }, to: null },
  { id: 'propose', cap: 'A proposal to review, not an action taken', act: async p => { await p.click('.chips [data-k=leave]'); await p.waitForSelector('[data-a=leave-apply]'); await p.waitForTimeout(500) }, to: '[data-a=leave-apply]' },
  { id: 'applied', cap: 'Applied, with an undo', act: async p => { await p.click('.chips [data-k=leave]'); await p.click('[data-a=leave-apply]'); await p.waitForTimeout(500) }, to: '.ctx [data-k=tax]' },
  { id: 'tax', cap: 'Answers that compare, with their sources', act: async p => { await p.click('.ctx [data-k=tax]'); await p.waitForSelector('[data-a=tax-set]'); await p.waitForTimeout(900) }, to: '[data-a=tax-set]' },
]

;(async () => {
  const b = await chromium.launch(); const data = {}
  for (const [key, url, frames] of [['agentic', OC, AGENTIC], ['engaze', EG, ENGAZE]]) {
    fs.mkdirSync(`${OUT}/${key}`, { recursive: true }); data[key] = []
    for (const f of frames) {
      const p = await b.newPage({ viewport: { width: W, height: H }, deviceScaleFactor: 2 })
      if (url === OC) await p.emulateMedia({ reducedMotion: 'reduce' })
      await p.goto(url); await p.evaluate(() => document.fonts.ready)
      await p.addStyleTag({ content: '.coach,.coach-min{display:none!important}' })
      if (f.js) await p.evaluate(f.js + (url === OC ? ';render();scrollTo(0,0)' : ''))
      if (f.act) { await p.evaluate(hello); await f.act(p) }
      await p.waitForTimeout(250)
      const box = f.to ? await p.evaluate(s => { const e = document.querySelector(s); if (!e) return null; const r = e.getBoundingClientRect(); return [Math.round(r.left + r.width / 2), Math.round(r.top + r.height / 2)] }, f.to) : null
      const png = `/tmp/shot-${key}-${f.id}.png`; await p.screenshot({ path: png }); await p.close()
      execFileSync('python3', ['-c', `from PIL import Image;Image.open('${png}').convert('RGB').save('${OUT}/${key}/${f.id}.webp','WEBP',quality=86,method=6)`])
      data[key].push({ img: `${key}/${f.id}.webp`, cap: f.cap, to: box })
      console.log(key, f.id, box)
    }
  }
  fs.writeFileSync('src/film/loops/shotsData.ts', `// Generated by tools/covers/shots.cjs. Frames of the working prototypes at the preview window's size, and where the cursor goes on each.\nexport type ShotFrame = { img: string; cap: string; to: [number, number] | null }\nexport const SHOTS: Record<string, ShotFrame[]> = ${JSON.stringify(data, null, 1)}\n`)
  await b.close()
})()
